def _canonical_rows(raw, model):
    out = {}
    for r in raw:
        if r['model'] != model:
            continue
        split = r['split']
        if split not in SPLITS:
            raise RuntimeError(f'Unexpected split for {model}: {split}')
        clip_id = r['clip_id'].replace('\\', '/')
        speaker = r['speaker']
        if '/' not in clip_id or clip_id.split('/')[0] != speaker:
            raise RuntimeError(f'ID/speaker mismatch: {model} {clip_id} / {speaker}')
        key = (split, clip_id)
        if key in out:
            raise RuntimeError(f'Duplicate prediction {model}: {key}')
        prob = float(r['probability'])
        label = int(r['true_label'])
        pred = int(r['predicted_label'])
        t = float(r['threshold'])
        if not (0 <= prob <= 1 and pred in (0, 1) and label in (0, 1)):
            raise RuntimeError(f'Invalid probability/class {model}: {key}')
        if pred != int(prob >= t):
            raise RuntimeError(f'Prediction inconsistent with locked threshold: {model}: {key}')
        if split == 'test' and r['condition'] != 'clean':
            raise RuntimeError(f'Unexpected clean condition for {key}')
        if split == 'test_degraded' and r['condition'] == 'clean':
            raise RuntimeError(f'Unexpected degraded condition for {key}')
        out[key] = dict(model=model, split=split, clip_id=clip_id, speaker=speaker,
                        label=label, pred=pred, prob=prob,
                        threshold=t, condition=r['condition'])
    if len(out) != 2*EXPECTED_N:
        raise RuntimeError(f'{model} has {len(out)} rows; expected {2*EXPECTED_N:,}. '
                           'Run improvedCQCC_evaluate.py --model all first.')
    for split in SPLITS:
        if sum(k[0] == split for k in out) != EXPECTED_N:
            raise RuntimeError(f'Incomplete {model} {split}')
    return out


def load_all(baseline_path, proposed_path):
    raw = read_csv(baseline_path)
    proposed_raw = read_csv(proposed_path)
    systems = {m: _canonical_rows(raw, m) for m in MODELS}
    systems[PROPOSED] = _canonical_rows(proposed_raw, PROPOSED)
    master = systems[PROPOSED]
    master_keys = set(master)
    for name, records in systems.items():
        if set(records) != master_keys:
            missing = sorted(master_keys - set(records))[:3]
            extra = sorted(set(records) - master_keys)[:3]
            raise RuntimeError(f'Unaligned recording IDs in {name}: missing={missing} extra={extra}')
        for k, r in records.items():
            source = master[k]
            if (r['label'] != source['label'] or r['speaker'] != source['speaker'] or
                    r['condition'] != source['condition']):
                raise RuntimeError(f'Metadata mismatch {name}: {k}')
    clean_keys = {k[1] for k in master if k[0]=='test'}
    deg_keys = {k[1] for k in master if k[0]=='test_degraded'}
    if clean_keys != deg_keys:
        raise RuntimeError('Clean/degraded recordings do not have exactly matching IDs.')
    for clip_id in clean_keys:
        a = master[('test', clip_id)]
        b = master[('test_degraded', clip_id)]
        if (a['label'], a['speaker']) != (b['label'], b['speaker']):
            raise RuntimeError(f'Clean/degraded pairing mismatch {clip_id}')
    for model, records in systems.items():
        for split in SPLITS:
            data=[r for k,r in records.items() if k[0] == split]
            tn=sum(x['label']==0 and x['pred']==0 for x in data)
            fp=sum(x['label']==0 and x['pred']==1 for x in data)
            fn=sum(x['label']==1 and x['pred']==0 for x in data)
            tp=sum(x['label']==1 and x['pred']==1 for x in data)
            got=(tn,fp,fn,tp)
            expected=EXPECTED_CONFUSIONS[model][split]
            if got!=expected:
                raise RuntimeError(f'CSV results differ from latest thesis results: '
                                   f'{model}/{split}: CM={got} expected={expected}. '
                                   'Do not report significance for mismatched checkpoints.')
    speakers = sorted({r['speaker'] for r in master.values()})
    if len(speakers)!=EXPECTED_SPEAKERS:
        raise RuntimeError(f'Expected {EXPECTED_SPEAKERS} speakers, saw {speakers}')
    return systems, speakers


def export_proposed(out_path):
    if out_path.exists():
        print(f'Proposed recording scores already exported: {out_path} (not overwriting)')
        return
    from improvedCQCC_config import FEATURES_DIR
    from improvedCQCC_cqcc_f0_fusion import _get_fusion
    print('Loading the EXISTING proposed experts and temporal fusion (inference only).')
    api, modules = _get_fusion()
    api.patch_experiment()
    api.preflight_checkpoint(final=True)
    artifact=api.read_new_artifact()
    net, device = api.load_new_net(artifact)
    base=modules['improvedCQCC_cqcc_f0_fusion_v19_calibrated']
    v28=modules['improvedCQCC_v28_temporal_evidence_fusion']
    win=modules['improvedCQCC_cqcc_f0_fusion_v22_window_level']
    t = float(artifact['threshold'])
    if not (0 < t < 1): raise RuntimeError(f'Bad saved threshold: {t}')
    rows=[]
    expected_cm={'test':(3404,125,366,3136),'test_degraded':(3136,393,358,3144)}
    for split in SPLITS:
        files=base.get_split_files(split)
        if len(files)!=EXPECTED_N:
            raise RuntimeError(f'Missing/extra feature files for {split}: {len(files)}')
        print(f'  Proposed saved-checkpoint inference: {split} ({len(files):,} clips)')
        # These are exactly the original, tested proposed-model inference paths.
        records=base.collect_expert_predictions(files,final=True)
        probs,delta=v28.inference(records,artifact,net,device)
        if len(records)!=EXPECTED_N or len(probs)!=EXPECTED_N or not np.isfinite(probs).all():
            raise RuntimeError('Incomplete proposed inference')
        y=np.asarray([int(r['label']) for r in records],dtype=int)
        met=win.calculate_metrics(y,probs,t)
        cm=tuple(np.asarray(met['cm'],dtype=int).ravel())
        if cm != expected_cm[split]:
            raise RuntimeError(f'Proposed checkpoint/result mismatch for {split}: '
                               f'confusion={cm}, expected={expected_cm[split]}. '
                               'STOP: check the latest tested models/features before statistical testing.')
        print(f'    Threshold={t:.3f}, F1={met["f1"]:.4f}, CM={cm}')
        for r,prob in zip(records,probs):
            filename=path_key(r['path'])
            origpath=Path(FEATURES_DIR)/split/filename
            if Path(r['path']).resolve()!=origpath.resolve():
                raise RuntimeError(f'Unexpected path location: {r["path"]}')
            speaker=str(r['speaker']);condition=str(r['condition'])
            if filename.split('/')[0]!=speaker:raise RuntimeError('Speaker/key mismatch')
            rows.append(dict(model=PROPOSED, split=split, condition=condition,
                             speaker=speaker,clip_id=filename,
                             true_label=int(r['label']),predicted_label=int(float(prob)>=t),
                             probability=float(prob),threshold=t))
    out_path.parent.mkdir(parents=True,exist_ok=True)
    # No source checkpoints/results modified; new CSV created in isolated output.
    if out_path.exists():raise RuntimeError(f'Refusing to overwrite {out_path}')
    write_csv(out_path, rows,['model','split','condition','speaker','clip_id','true_label',
                              'predicted_label','probability','threshold'])
    print(f'  Saved proposed per-recording predictions: {out_path}')


def paired_data(systems,speakers,model_a,model_b,split):
    keys=sorted([key for key in systems[PROPOSED] if key[0]==split])
    a=systems[model_a];b=systems[model_b]
    y=np.asarray([a[k]['label'] for k in keys],dtype=np.int8)
    pa=np.asarray([a[k]['pred'] for k in keys],dtype=np.int8)
    pb=np.asarray([b[k]['pred'] for k in keys],dtype=np.int8)
    s=np.asarray([a[k]['speaker'] for k in keys],dtype=object)
    groups=[np.flatnonzero(s==speaker) for speaker in speakers]
    assert all(len(indices)>0 for indices in groups)
    return y,pa,pb,groups


def exact_swap_test(y,a,b,groups,observed):
    # The randomized unit is a whole speaker's set of paired recordings.
    null=[]
    for switches in itertools.product((False, True), repeat=len(groups)):
        pa=a.copy();pb=b.copy()
        for i,flip in enumerate(switches):
            if flip:
                ix=groups[i];pa[ix]=b[ix];pb[ix]=a[ix]
        null.append(f1_from_predictions(y,pa)-f1_from_predictions(y,pb))
    null=np.asarray(null)
    # Add tiny floating tolerance for comparisons of mathematically equal values.
    p=float(np.count_nonzero(np.abs(null)>=abs(observed)-1e-12)/len(null))
    return max(p,1/len(null)),len(null)


def cluster_bootstrap(y,a,b,groups,iterations,rng):
    differences=np.empty(iterations,dtype=float)
    for i in range(iterations):
        choices=rng.integers(0,len(groups),size=len(groups))
        selected=np.concatenate([groups[g] for g in choices])
        differences[i]=f1_from_predictions(y[selected],a[selected])-f1_from_predictions(y[selected],b[selected])
    return np.percentile(differences,[2.5,97.5])


def speaker_rows(y,a,b,groups,speakers,split,model_b):
    return [dict(speaker=speaker,split=split,contrast_model=model_b,
                 n=int(len(g)),proposed_f1=float(f1_from_predictions(y[g],a[g])),
                 comparator_f1=float(f1_from_predictions(y[g],b[g])),
                 delta_f1_pp=100*(f1_from_predictions(y[g],a[g])-f1_from_predictions(y[g],b[g])))
            for speaker,g in zip(speakers,groups)]


def make_figure(rows,path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig,ax=plt.subplots(figsize=(8.2,4.2))
    speakers=sorted(set(r['speaker'] for r in rows))
    # The proposed–CNN-GRU contrast is displayed for clean and degraded speech.
    for split,offset,marker,color,lab in (
       ('test',+0.14,'o','#8b949e','Clean'),
       ('test_degraded',-0.14,'D','#1966b5','Degraded')):
        values={r['speaker']:r['delta_f1_pp'] for r in rows
                if r['contrast_model']=='CNN-GRU' and r['split']==split}
        if len(values)!=len(speakers):raise RuntimeError('Incomplete speaker figure data')
        ax.scatter([values[s] for s in speakers],np.arange(len(speakers))+offset,
                   marker=marker,s=52,c=color,edgecolors='white',linewidths=.6,
                   label=lab,zorder=3)
    ax.axvline(0,color='#666666',linewidth=1,linestyle='--')
    ax.set_yticks(np.arange(len(speakers)),speakers)
    ax.set_xlabel('Proposed minus CNN–GRU F1 (percentage points)')
    ax.set_ylabel('Held-out speaker ID')
    ax.set_title('Speaker-level F1 differences: proposed fusion vs CNN–GRU')
    ax.legend(frameon=False,loc='best')
    ax.grid(axis='x',alpha=.16)
    ax.invert_yaxis()
    fig.tight_layout()
    path.parent.mkdir(parents=True,exist_ok=True)
    fig.savefig(path,dpi=260,bbox_inches='tight')
    fig.savefig(path.with_suffix('.svg'),bbox_inches='tight')
    plt.close(fig)


def fmt_number(v):
    return f'{v:+.2f}'


def findrow(rows,name,split):
    return next(r for r in rows if r['comparison']==name and r['split']==split)


def write_report(rows,speaker_records,out,speakers,iterations):
    # One table + one figure + one discussion, with methodological notes outside text.
    labels={ 'CNN-only':'Proposed − CNN-only',
             'CNN-GRU':'Proposed − CNN–GRU',
             'CNN-GRU-F':'Proposed − CNN–GRU–F',
             'Proposed clean − degraded':'Proposed clean − degraded'}
    lines=['# E.5. Model Generalization and Statistical Reliability','',
           'The following comparisons are exploratory because the speaker-disjoint held-out set informed earlier model-development decisions. '
           'Differences are computed from paired recording predictions at each model\'s saved threshold. '
           'Eight held-out speakers, rather than individual windows or recordings, form the independent resampling units.','',
           '**Table 4.X. Speaker-clustered paired F1-score comparisons**','',
           '| Comparison | Condition | ΔF1 (pp) | 95% CI (pp) | Two-sided p |',
           '|:--|:--|--:|:--|--:|']
    for r in rows:
        name=labels[r['comparison']]
        c='Clean' if r['split']=='test' else ('Degraded' if r['split']=='test_degraded' else 'Clean − degraded')
        lines.append(f'| {name} | {c} | {fmt_number(r["delta_f1_pp"])} | '
                     f'[{fmt_number(r["ci_lower_pp"])}, {fmt_number(r["ci_upper_pp"])}] | '
                     f'{r["p_exact"]:.4f} |')
    lines+=['',
       '*Note.* Positive differences in the first six rows favor the proposed model. '
       'The last row shows the proposed model\'s reduction from clean to degraded speech. '
       f'95% intervals use {iterations:,} speaker-cluster bootstrap resamples; '
       'p-values are two-sided exact whole-speaker paired-swap permutation tests '
       f'({2**len(speakers)} assignments). These exploratory intervals and p-values '
       'are not adjusted for the six model contrasts or for earlier held-out model selection.','',
       '**Figure 4.X. Speaker-level F1 differences between the proposed model and CNN–GRU**','',
       '![Speaker-level paired F1 differences](figures/e5_speaker_paired_f1.png)','',
       '*Figure note.* Each paired pair of symbols represents one held-out speaker. '
       'Values to the right of zero favor the proposed model at the indicated condition. '
       'Speaker-level F1 is not simply averaged to calculate overall pooled F1.','']
    clean_gru=findrow(rows,'CNN-GRU','test')
    deg_gru=findrow(rows,'CNN-GRU','test_degraded')
    deg_cnn=findrow(rows,'CNN-only','test_degraded')
    h4=findrow(rows,'Proposed clean − degraded','paired')
    consistent_clean=sum(r['delta_f1_pp']>0 for r in speaker_records if r['contrast_model']=='CNN-GRU' and r['split']=='test')
    consistent_deg=sum(r['delta_f1_pp']>0 for r in speaker_records if r['contrast_model']=='CNN-GRU' and r['split']=='test_degraded')
    def evidence(row):
        if row['p_exact']<.05 and row['ci_lower_pp']>0:
            return 'supported a positive paired F1 difference in this exploratory comparison'
        if row['p_exact']<.05 and row['ci_upper_pp']<0:
            return 'supported a negative paired F1 difference in this exploratory comparison'
        return 'did not establish a statistically detectable paired F1 difference'
    discussion=(
       f'The proposed CNN–GRU–CQCC–F0 prediction-level fusion system was evaluated against the same eight '
       f'held-out speakers as the three comparison models. Compared with the Log-Mel CNN–GRU baseline, '
       f'its F1 difference was {clean_gru["delta_f1_pp"]:+.2f} percentage points on clean speech and '
       f'{deg_gru["delta_f1_pp"]:+.2f} points on degraded speech. The exact speaker-paired tests '
       f'{evidence(clean_gru)} for clean speech and {evidence(deg_gru)} for degraded speech. '
       f'The speaker-level plot shows positive F1 differences for {consistent_clean} of {len(speakers)} '
       f'speakers under clean conditions and {consistent_deg} of {len(speakers)} under degradation, '
       f'indicating whether the aggregate gain is consistent across speakers. '
       f'Against CNN-only, the degraded F1 difference was {deg_cnn["delta_f1_pp"]:+.2f} points. '
       f'Within the proposed system, F1 decreased by {h4["delta_f1_pp"]:.2f} points after degradation; '
       f'this is within the prespecified ten-percentage-point practical tolerance, but the paired '
       f'test {"detected a clean–degraded difference" if h4["p_exact"]<.05 else "did not establish a clean–degraded difference"} '
       f'(p = {h4["p_exact"]:.4f}). '
       f'Because the unit of independent variation is the speaker (n = {len(speakers)}) and the held-out '
       f'set had informed earlier research choices, these findings provide exploratory evidence, not '
       f'confirmatory proof of superiority or robustness. The complete H1 claim additionally requires '
       f'consideration of accuracy, precision, recall, ROC-AUC, and EER, rather than F1 alone.'
    )
    lines+=['**Discussion.** '+discussion,'',
            '*Interpretive scope.* The recorded p-values concern F1 only. They do not establish that '
            'all metrics differ, nor do they isolate the independent effects of CQCC, F0 and causal temporal correction. '
            'No exhaustive tuning or new training was performed for this analysis.','']
    (out/'README.md').write_text('\n'.join(lines),encoding='utf-8')
    return discussion


def analyze(baseline_path, proposed_path, out, iterations):
    systems,speakers=load_all(baseline_path,proposed_path)
    out.mkdir(parents=True,exist_ok=True)
    rng=np.random.default_rng(SEED)
    rows=[];speaker_records=[]
    for split in SPLITS:
        for model in MODELS:
            y,a,b,groups=paired_data(systems,speakers,PROPOSED,model,split)
            delta=f1_from_predictions(y,a)-f1_from_predictions(y,b)
            ci=cluster_bootstrap(y,a,b,groups,iterations,rng)
            p,nperm=exact_swap_test(y,a,b,groups,delta)
            rows.append(dict(comparison=model,split=split,n=int(len(y)),
                             n_speakers=len(speakers),delta_f1_pp=100*delta,
                             ci_lower_pp=100*ci[0],ci_upper_pp=100*ci[1],
                             p_exact=p,n_permutations=nperm,
                             proposed_accuracy=accuracy(y,a),comparator_accuracy=accuracy(y,b),
                             proposed_f1=f1_from_predictions(y,a),comparator_f1=f1_from_predictions(y,b)))
            speaker_records.extend(speaker_rows(y,a,b,groups,speakers,split,model))
    # H4: clean/degraded counterparts of the identical held-out recordings.
    clean_keys=sorted(k for k in systems[PROPOSED] if k[0]=='test')
    orig=systems[PROPOSED]
    y=np.array([orig[k]['label'] for k in clean_keys],dtype=np.int8)
    a=np.array([orig[k]['pred'] for k in clean_keys],dtype=np.int8)
    b=np.array([orig[('test_degraded',k[1])]['pred'] for k in clean_keys],dtype=np.int8)
    ss=np.array([orig[k]['speaker'] for k in clean_keys],dtype=object)
    groups=[np.flatnonzero(ss==s) for s in speakers]
    delta=f1_from_predictions(y,a)-f1_from_predictions(y,b)
    ci=cluster_bootstrap(y,a,b,groups,iterations,rng)
    p,nperm=exact_swap_test(y,a,b,groups,delta)
    rows.append(dict(comparison='Proposed clean − degraded',split='paired',n=len(y),
                     n_speakers=len(speakers),delta_f1_pp=100*delta,
                     ci_lower_pp=100*ci[0],ci_upper_pp=100*ci[1],
                     p_exact=p,n_permutations=nperm,
                     proposed_accuracy=accuracy(y,a),comparator_accuracy=accuracy(y,b),
                     proposed_f1=f1_from_predictions(y,a),comparator_f1=f1_from_predictions(y,b)))
    write_csv(out/'e5_paired_statistics.csv',rows,list(rows[0]))
    write_csv(out/'e5_speaker_f1.csv',speaker_records,list(speaker_records[0]))
    make_figure(speaker_records,out/'figures'/'e5_speaker_paired_f1.png')
    discussion=write_report(rows,speaker_records,out,speakers,iterations)
    manifest=dict(method='Speaker-cluster bootstrap CI and exact 2-sided within-speaker label-swap permutation',
                  independent_units=len(speakers),random_seed=SEED,bootstrap_iterations=iterations,
                  assignments=2**len(speakers),not_multitest_adjusted=True,
                  post_selection_exploratory=True,
                  sources=[str(baseline_path),str(proposed_path)])
    (out/'e5_method_metadata.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    print('\nE.5 SPEAKER-CLUSTERED PAIR COMPARISONS (exploratory):')
    for r in rows:
        print(f"  {r['comparison']:<28} {r['split']:<13} "
              f"deltaF1={r['delta_f1_pp']:+6.2f} pp "
              f"CI=[{r['ci_lower_pp']:+6.2f},{r['ci_upper_pp']:+6.2f}] "
              f"p={r['p_exact']:.4f}")
    print(f'\nGenerated: {out}/README.md')
    print(f'One figure: {out}/figures/e5_speaker_paired_f1.png')
    print('WARNING: eight speakers; unadjusted exploratory inference, NOT independent held-out confirmation.')
    return rows


def self_test():
    rng=np.random.default_rng(5)
    y=rng.integers(0,2,800)
    a=y.copy();b=y.copy()
    groups=[np.arange(k*100,(k+1)*100) for k in range(8)]
    delta=0.0
    p,n=exact_swap_test(y,a,b,groups,delta)
    assert n==256 and p==1.0
    ci=cluster_bootstrap(y,a,b,groups,50,rng)
    assert np.allclose(ci,[0,0])
    assert np.isclose(f1_from_predictions(np.array([1,1,0]),np.array([1,0,1])),.5)
    print('PASS: exact 256-swap permutation, clustered bootstrap, metric checks.')


