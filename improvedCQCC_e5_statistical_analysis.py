def path_key(path):
    path = Path(str(path))
    return f'{path.parent.name}/{path.name}'


def f1_from_predictions(y, predictions):
    y = np.asarray(y, dtype=np.int8)
    predictions = np.asarray(predictions, dtype=np.int8)
    tp = np.count_nonzero((y == 1) & (predictions == 1))
    fp = np.count_nonzero((y == 0) & (predictions == 1))
    fn = np.count_nonzero((y == 1) & (predictions == 0))
    denom = 2 * tp + fp + fn
    return 2.0 * tp / denom if denom else 0.0


def accuracy(y, p):
    return float(np.mean(np.asarray(y) == np.asarray(p)))


def write_csv(path, rows, fields):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8-sig', newline='') as f:
        wr = csv.DictWriter(f, fieldnames=fields, extrasaction='ignore')
        wr.writeheader()
        wr.writerows(rows)


def read_csv(path):
    if not path.is_file():
        raise FileNotFoundError(f'Missing required CSV: {path}')
    with path.open('r', encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


def paths():
    from improvedCQCC_config import RESULTS_DIR
    base = Path(RESULTS_DIR)
    out = base / 'e5_statistical_reliability'
