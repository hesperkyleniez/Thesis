"""E.5: exploratory speaker-clustered paired comparisons; read-only inference.

Uses the EXISTING three-baseline per-recording CSV generated by
improvedCQCC_evaluate.py and exports the final AUC-selected Akıncı–Özbay CQCC
+ F0 v28-temporal proposed model's per-recording scores using its SAVED weights.
No fitting, feature regeneration, augmentation, checkpoint changes or held-out
threshold selection takes place here.

Outputs one Chapter 4 E.5 README, one compact statistical table, one figure,
and supporting CSVs under RESULTS_DIR/e5_statistical_reliability.

Statistical design: eight SPEAKER clusters, exact paired whole-speaker swap
permutation test (256 allocations), and speaker-cluster bootstrap (95% percentile
CI). Comparisons use pre-existing classification thresholds; p-values are
exploratory and not multiple-comparison adjusted. The previously used held-out
set is NOT an independent confirmatory test set.
"""
